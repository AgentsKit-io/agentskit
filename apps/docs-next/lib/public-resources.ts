export const PUBLIC_RESOURCE_TYPES = [
  'official',
  'article',
  'directory',
  'registry',
  'recognition',
  'community',
] as const

export const PUBLIC_RESOURCE_STATUSES = ['live', 'published', 'verified'] as const

export type PublicResourceType = (typeof PUBLIC_RESOURCE_TYPES)[number]
export type PublicResourceStatus = (typeof PUBLIC_RESOURCE_STATUSES)[number]

export type PublicResource = Readonly<{
  id: string
  title: string
  summary: string
  product: string
  publisher: string
  type: PublicResourceType
  status: PublicResourceStatus
  url: string
  verifiedAt: string
  topics: readonly string[]
}>

function ecosystemUrl(productId: string, path = ''): string {
  const product = ecosystem.properties.find((candidate) => candidate.id === productId)

  if (!product) {
    throw new Error(`Unknown ecosystem product: ${productId}`)
  }

  return new URL(path, product.url).toString()
}

